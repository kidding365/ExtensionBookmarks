/**
 * ExtensionBookmarks - Background Service Worker
 * Manages event listeners, periodic alarms, keyboard shortcuts, and sync triggers.
 */

import { stashService } from '../stash/stash-service.js';
import { bookmarkManager } from '../bookmarks/manager.js';
import { diffEngine } from '../sync/diff-engine.js';
import { idStore } from '../sync/id-store.js';
import { DEFAULT_SETTINGS } from '../models/types.js';

let syncDebounceTimer = null;
const SYNC_DEBOUNCE_MS = 5000;

// Initialize on install or startup
chrome.runtime.onInstalled.addListener(async () => {
  console.log('[ExtensionBookmarks] Service worker installed.');
  await idStore.init();
  await stashService.init();

  // Create Context Menus
  chrome.contextMenus.removeAll(() => {
    chrome.contextMenus.create({
      id: 'eb_stash_window',
      title: 'Stash all tabs into Stored Pages',
      contexts: ['action', 'page']
    });
    chrome.contextMenus.create({
      id: 'eb_stash_tab',
      title: 'Stash this tab into Stored Pages',
      contexts: ['page', 'action']
    });
    chrome.contextMenus.create({
      id: 'eb_open_dashboard',
      title: 'Open ExtensionBookmarks Dashboard',
      contexts: ['action']
    });
  });

  // Schedule auto-sync alarm
  setupAutoSyncAlarm();
});

chrome.runtime.onStartup.addListener(async () => {
  await idStore.init();
  await stashService.init();
  setupAutoSyncAlarm();
});

async function setupAutoSyncAlarm() {
  const { eb_settings } = await chrome.storage.local.get('eb_settings');
  const settings = { ...DEFAULT_SETTINGS, ...(eb_settings || {}) };

  const interval = settings.autoSyncIntervalMinutes || 10;
  if (interval > 0) {
    chrome.alarms.create('eb_auto_sync_alarm', { periodInMinutes: interval });
  } else {
    chrome.alarms.clear('eb_auto_sync_alarm');
  }
}

// Alarms listener
chrome.alarms.onAlarm.addListener(async (alarm) => {
  if (alarm.name === 'eb_auto_sync_alarm') {
    const { eb_settings } = await chrome.storage.local.get('eb_settings');
    const settings = { ...DEFAULT_SETTINGS, ...(eb_settings || {}) };
    if (settings.githubToken && settings.gistId) {
      await diffEngine.runSync(settings);
    }
  }
});

// Context Menu actions
chrome.contextMenus.onClicked.addListener(async (info) => {
  if (info.menuItemId === 'eb_stash_window') {
    await stashService.stashCurrentWindow();
  } else if (info.menuItemId === 'eb_stash_tab') {
    await stashService.stashActiveTab();
  } else if (info.menuItemId === 'eb_open_dashboard') {
    openDashboard();
  }
});

// Keyboard commands listener
chrome.commands.onCommand.addListener(async (command) => {
  if (command === 'stash-window') {
    await stashService.stashCurrentWindow();
  } else if (command === 'stash-tab') {
    await stashService.stashActiveTab();
  } else if (command === 'open-dashboard') {
    openDashboard();
  }
});

function openDashboard() {
  const dashboardUrl = chrome.runtime.getURL('src/ui/dashboard/dashboard.html');
  chrome.tabs.query({}, (tabs) => {
    const existing = tabs.find(t => t.url && t.url.startsWith(dashboardUrl));
    if (existing) {
      chrome.tabs.update(existing.id, { active: true });
      if (existing.windowId) chrome.windows.update(existing.windowId, { focused: true });
    } else {
      chrome.tabs.create({ url: dashboardUrl });
    }
  });
}

// Debounced Sync Trigger for Local Bookmark Changes
function triggerDebouncedSync() {
  if (bookmarkManager.isApplyingSync) {
    // Ignore events generated by our own sync engine
    return;
  }

  if (syncDebounceTimer) clearTimeout(syncDebounceTimer);
  syncDebounceTimer = setTimeout(async () => {
    const { eb_settings } = await chrome.storage.local.get('eb_settings');
    const settings = { ...DEFAULT_SETTINGS, ...(eb_settings || {}) };
    if (settings.githubToken && settings.gistId) {
      await diffEngine.runSync(settings);
    }
  }, SYNC_DEBOUNCE_MS);
}

// Bookmark listeners
chrome.bookmarks.onCreated.addListener((id, bookmark) => {
  triggerDebouncedSync();
});

chrome.bookmarks.onChanged.addListener((id, changeInfo) => {
  triggerDebouncedSync();
});

chrome.bookmarks.onMoved.addListener((id, moveInfo) => {
  triggerDebouncedSync();
});

chrome.bookmarks.onRemoved.addListener((id, removeInfo) => {
  idStore.deleteMapping(id);
  triggerDebouncedSync();
});

// Message Listener for UI Actions
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  (async () => {
    try {
      if (message.type === 'TRIGGER_SYNC') {
        const { eb_settings } = await chrome.storage.local.get('eb_settings');
        const settings = { ...DEFAULT_SETTINGS, ...(eb_settings || {}) };
        const result = await diffEngine.runSync(settings, message.options);
        sendResponse({ success: true, result });
      } else if (message.type === 'STASH_WINDOW') {
        const res = await stashService.stashCurrentWindow(message.folderId);
        sendResponse({ success: true, res });
      } else if (message.type === 'STASH_TAB') {
        const res = await stashService.stashActiveTab(message.folderId);
        sendResponse({ success: true, res });
      } else if (message.type === 'OPEN_DASHBOARD') {
        openDashboard();
        sendResponse({ success: true });
      }
    } catch (err) {
      sendResponse({ success: false, error: err.message });
    }
  })();
  return true; // async sendResponse
});
